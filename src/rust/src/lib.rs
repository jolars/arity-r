#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn verified_and_single_pass_formatting_agree() {
        let source = "x<-(1+2)*3^4\n";
        let verified = format_source(source, 80, 2, "auto", false, true).unwrap();
        let single = format_source(source, 80, 2, "auto", false, false).unwrap();

        assert_eq!(verified, "x <- (1 + 2) * 3^4\n");
        assert_eq!(single, verified);
    }

    #[test]
    fn native_validation_rejects_invalid_options() {
        assert!(format_source("x\n", 0, 2, "auto", false, true).is_err());
        assert!(format_source("x\n", 80, 2, "windows", false, true).is_err());
    }
}
